import XCTest

final class OfflineFlowTests: XCTestCase {
    @MainActor func testFullJourney() {
        let app = XCUIApplication()
        app.launchArguments = ["-ui-testing", "-reset-test-store"]
        app.launch()
        app.buttons["Add activity"].tap()
        app.textFields["Activity name"].tap()
        app.textFields["Activity name"].typeText("Walk")
        app.buttons["Save activity"].tap()
        XCTAssertTrue(app.buttons["Log Walk"].waitForExistence(timeout: 10))
        app.buttons["Log Walk"].tap()
        XCTAssertTrue(app.staticTexts["1 of 1 completions"].waitForExistence(timeout: 5))
        app.buttons["Open Walk"].tap()
        app.buttons["Edit recorded history"].tap()
        app.cells.firstMatch.tap()
        app.switches["Include actual time"].coordinate(withNormalizedOffset: CGVector(dx: 0.9, dy: 0.5)).tap()
        app.buttons["Save entry"].tap()
        XCTAssertTrue(app.staticTexts["Date only"].waitForExistence(timeout: 5))
        app.navigationBars.buttons.firstMatch.tap()
        app.buttons["Progress reports"].tap()
        XCTAssertTrue(app.staticTexts["Calendar"].waitForExistence(timeout: 5))
        app.navigationBars.buttons.firstMatch.tap()
        app.buttons["Reminders"].tap()
        XCTAssertEqual(app.switches["Reminders"].value as? String, "0")
        app.buttons["Save reminder settings"].tap()
        XCTAssertTrue(app.buttons["Home Screen shortcut"].waitForExistence(timeout: 5))
        app.buttons["Home Screen shortcut"].tap()
        XCTAssertTrue(app.staticTexts["Set up a shortcut for Walk"].waitForExistence(timeout: 5))
        app.navigationBars.buttons.firstMatch.tap()
        app.buttons["Delete activity"].tap()
        app.alerts.buttons["Cancel"].tap()
        XCTAssertTrue(app.navigationBars["Walk"].exists)
        app.navigationBars.buttons.firstMatch.tap()
        app.buttons["Settings"].tap()
        app.buttons["Export history"].tap()
        app.buttons["Export CSV"].tap()
        XCTAssertTrue(app.buttons["Close"].waitForExistence(timeout: 10))
        app.buttons["Close"].tap()
        XCTAssertTrue(app.navigationBars["Export history"].waitForExistence(timeout: 5))
        app.terminate()
        app.launchArguments = ["-ui-testing"]
        app.launch()
        XCTAssertTrue(app.staticTexts["1 of 1 completions"].waitForExistence(timeout: 10))
        app.buttons["Open Walk"].tap()
        app.buttons["Edit recorded history"].tap()
        XCTAssertTrue(app.staticTexts["Date only"].waitForExistence(timeout: 5))
    }
}
